-- Un certificato verificato, firmato o in vigore non cambia piu' nel contenuto: cambiano
-- solo lo stato e le date delle transizioni. Una correzione e' una revisione nuova.
CREATE FUNCTION metrology.certificate_content_locked() RETURNS trigger
    LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'i certificati non si cancellano' USING ERRCODE = 'restrict_violation';
    END IF;
    IF OLD.status IN ('SIGNED', 'VERIFIED', 'EFFECTIVE', 'SUPERSEDED', 'SUPERSEDED_BY_CONFIG', 'INVALIDATED')
       AND (NEW.function IS DISTINCT FROM OLD.function
            OR NEW.covariance IS DISTINCT FROM OLD.covariance
            OR NEW.number IS DISTINCT FROM OLD.number
            OR NEW.revision IS DISTINCT FROM OLD.revision
            OR NEW.subject_type IS DISTINCT FROM OLD.subject_type
            OR NEW.subject_id IS DISTINCT FROM OLD.subject_id
            OR NEW.calibrated_min IS DISTINCT FROM OLD.calibrated_min
            OR NEW.calibrated_max IS DISTINCT FROM OLD.calibrated_max
            OR NEW.calibration_date IS DISTINCT FROM OLD.calibration_date
            OR NEW.issue_date IS DISTINCT FROM OLD.issue_date
            OR NEW.lab_company_id IS DISTINCT FROM OLD.lab_company_id
            OR NEW.issuer IS DISTINCT FROM OLD.issuer
            OR NEW.xml_document_id IS DISTINCT FROM OLD.xml_document_id
            OR NEW.pdf_document_id IS DISTINCT FROM OLD.pdf_document_id
            OR NEW.original_document_id IS DISTINCT FROM OLD.original_document_id) THEN
        RAISE EXCEPTION 'certificato % in stato %: il contenuto non si modifica, si emette una revisione',
            OLD.id, OLD.status USING ERRCODE = 'restrict_violation';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER certificate_content_locked
    BEFORE UPDATE OR DELETE ON metrology.certificate
    FOR EACH ROW EXECUTE FUNCTION metrology.certificate_content_locked();

-- I punti di un certificato bloccato non si toccano.
CREATE FUNCTION metrology.certificate_point_locked() RETURNS trigger
    LANGUAGE plpgsql AS $$
DECLARE
    parent_status varchar(24);
BEGIN
    SELECT status INTO parent_status FROM metrology.certificate
     WHERE id = COALESCE(NEW.certificate_id, OLD.certificate_id);
    IF parent_status IN ('SIGNED', 'VERIFIED', 'EFFECTIVE', 'SUPERSEDED', 'SUPERSEDED_BY_CONFIG', 'INVALIDATED') THEN
        RAISE EXCEPTION 'i punti di un certificato in stato % non si modificano', parent_status
            USING ERRCODE = 'restrict_violation';
    END IF;
    RETURN COALESCE(NEW, OLD);
END;
$$;

CREATE TRIGGER certificate_point_locked
    BEFORE INSERT OR UPDATE OR DELETE ON metrology.certificate_point
    FOR EACH ROW EXECUTE FUNCTION metrology.certificate_point_locked();

