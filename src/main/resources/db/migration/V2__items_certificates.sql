-- Fase 1 del piano (I1): esemplari, campioni, documenti, certificati, ruoli metrologici,
-- aziende, registro delle azioni e outbox delle attivazioni [S §5.2].
--
-- Le immutabilita' si fanno rispettare qui, non solo nel codice: un documento, una riga di
-- audit e il contenuto di un certificato firmato non cambiano piu', qualunque cosa faccia
-- chi ha accesso al database.

-- ------------------------------------------------------------------ anagrafiche

-- I laboratori: il nostro e quelli esterni che emettono certificati. `recognized` dice se un
-- DCC firmato da loro salta direttamente a «verificato» [S §5.5].
CREATE TABLE metrology.lab_company (
    id                         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                       varchar(200) NOT NULL,
    address                    varchar(200),
    city                       varchar(100),
    postal_code                varchar(16),
    country                    varchar(2),
    accreditation_body         varchar(80),
    accreditation_number       varchar(80),
    accreditation_valid_until  date,
    internal                   boolean      NOT NULL DEFAULT false,
    recognized                 boolean      NOT NULL DEFAULT false,
    created_at                 timestamptz  NOT NULL DEFAULT now()
);

-- Le aziende cliente (decisione D-C): il «cliente» dell'Hub e l'intestatario dei DCC.
CREATE TABLE metrology.client_company (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         varchar(200) NOT NULL UNIQUE,
    address      varchar(200),
    city         varchar(100),
    postal_code  varchar(16),
    country      varchar(2),
    vat_number   varchar(32),
    created_at   timestamptz  NOT NULL DEFAULT now(),
    archived_at  timestamptz
);

-- Un utente Keycloak appartiene al piu' a un'azienda: la chiave e' il suo `sub`.
CREATE TABLE metrology.client_company_member (
    user_sub      varchar(64)  PRIMARY KEY,
    company_id    bigint       NOT NULL REFERENCES metrology.client_company(id),
    display_name  varchar(200),
    email         varchar(200),
    added_by      varchar(64)  NOT NULL,
    added_at      timestamptz  NOT NULL DEFAULT now()
);

-- I ruoli metrologici, con una validita' nel tempo che Keycloak non gestisce [S §9].
CREATE TABLE metrology.metrology_role (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_sub        varchar(64)  NOT NULL,
    display_name    varchar(200),
    role            varchar(24)  NOT NULL
        CHECK (role IN ('TECHNICIAN', 'APPROVER', 'TECHNICAL_MANAGER')),
    valid_from      date         NOT NULL,
    valid_to        date,
    -- Per un utente di un laboratorio esterno (ruolo app-lab): quale laboratorio.
    lab_company_id  bigint       REFERENCES metrology.lab_company(id),
    granted_by      varchar(64)  NOT NULL,
    granted_at      timestamptz  NOT NULL DEFAULT now(),
    CHECK (valid_to IS NULL OR valid_to >= valid_from)
);
CREATE INDEX idx_metrology_role_user ON metrology.metrology_role (user_sub);

-- --------------------------------------------------------------------- documenti

-- I file immutabili: PDF, DCC, grafici, report. Mai aggiornati: rigenerare crea un documento
-- nuovo. Il backup di Duplicati li copre perche' stanno nel database [S §5.8].
CREATE TABLE metrology.document (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sha256      varchar(64)  NOT NULL,
    mime        varchar(100) NOT NULL,
    size        bigint       NOT NULL CHECK (size >= 0),
    filename    varchar(255),
    kind        varchar(32)  NOT NULL,
    content     bytea        NOT NULL,
    -- Chi puo' scaricarlo oltre al personale del laboratorio: il proprietario dell'esemplare.
    owner_sub   varchar(64),
    created_by  varchar(64)  NOT NULL,
    created_at  timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX idx_document_sha256 ON metrology.document (sha256);

-- ---------------------------------------------------------------------- esemplari

-- L'esemplare tarato: un sensore fisico, con la chiave naturale (EUID della MU, indice) [M1].
CREATE TABLE metrology.calibrated_item (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mu_extended_id          bigint       NOT NULL,
    sensor_index            integer      NOT NULL,
    channel                 varchar(8),
    model_name              varchar(120),
    sensor_template_id      integer,
    sensor_template_major   integer,
    serial_number           varchar(80),
    owner_sub               varchar(64),
    requires_calibration    boolean      NOT NULL DEFAULT true,
    interval_override_days  integer      CHECK (interval_override_days IS NULL OR interval_override_days > 0),
    -- Il laboratorio esterno a cui e' affidato: i suoi utenti app-lab ne inseriscono i dati.
    assigned_lab_id         bigint       REFERENCES metrology.lab_company(id),
    status                  varchar(16)  NOT NULL DEFAULT 'IN_SERVICE'
        CHECK (status IN ('IN_SERVICE', 'REPLACED', 'RETIRED')),
    created_by              varchar(64)  NOT NULL,
    created_at              timestamptz  NOT NULL DEFAULT now(),
    UNIQUE (mu_extended_id, sensor_index)
);

-- I campioni di riferimento, esemplari a loro volta, con il certificato corrente [M2].
CREATE TABLE metrology.reference_standard (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                    varchar(120) NOT NULL,
    manufacturer            varchar(120),
    model                   varchar(120),
    serial_number           varchar(80)  NOT NULL UNIQUE,
    model_template_id       integer,
    model_template_major    integer,
    status                  varchar(16)  NOT NULL DEFAULT 'IN_SERVICE'
        CHECK (status IN ('IN_SERVICE', 'IN_CALIBRATION', 'RETIRED')),
    location                varchar(200),
    current_certificate_id  bigint,
    notes                   text,
    created_by              varchar(64)  NOT NULL,
    created_at              timestamptz  NOT NULL DEFAULT now()
);

-- -------------------------------------------------------------------- certificati

CREATE TABLE metrology.certificate (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind                   varchar(16)  NOT NULL CHECK (kind IN ('INTERNAL', 'EXTERNAL')),
    subject_type           varchar(16)  NOT NULL CHECK (subject_type IN ('ITEM', 'REFERENCE')),
    subject_id             bigint       NOT NULL,
    number                 varchar(64)  NOT NULL,
    revision               integer      NOT NULL DEFAULT 1 CHECK (revision >= 1),
    supersedes_id          bigint       REFERENCES metrology.certificate(id),
    amendment_reason       text,
    lab_company_id         bigint       REFERENCES metrology.lab_company(id),
    issuer                 varchar(200),
    issuer_accreditation   varchar(120),
    calibration_date       date,
    issue_date             date,
    -- La validita' la decide il nostro sistema, non il certificato [S §5.5].
    valid_until            timestamptz,
    status                 varchar(24)  NOT NULL
        CHECK (status IN ('DRAFT', 'ENTERED', 'APPROVED', 'SIGNED', 'VERIFIED', 'EFFECTIVE',
                          'SUPERSEDED', 'SUPERSEDED_BY_CONFIG', 'INVALIDATED')),
    source                 varchar(16)  NOT NULL CHECK (source IN ('ENGINE', 'DCC_XML', 'PDF_MANUAL')),
    -- La funzione dell'esemplare, nel formato del blocco `calibration` di un template.
    function               jsonb,
    covariance             jsonb,
    calibrated_min         double precision,
    calibrated_max         double precision,
    calibrated_dsi         varchar(80),
    -- L'esito dichiarato: alimenta i contatori dell'Hub senza interpretare un testo libero.
    conformity             varchar(16)  NOT NULL DEFAULT 'NOT_STATED'
        CHECK (conformity IN ('CONFORM', 'NON_CONFORM', 'NOT_STATED')),
    conformity_statement   text,
    decision_rule          varchar(200),
    ambient                jsonb,
    fingerprint            varchar(80),
    calibration_result_id  bigint,
    xml_document_id        bigint       REFERENCES metrology.document(id),
    pdf_document_id        bigint       REFERENCES metrology.document(id),
    original_document_id   bigint       REFERENCES metrology.document(id),
    created_by             varchar(64)  NOT NULL,
    created_at             timestamptz  NOT NULL DEFAULT now(),
    entered_by             varchar(64),
    entered_at             timestamptz,
    approved_by            varchar(64),
    approved_at            timestamptz,
    signed_at              timestamptz,
    verified_by            varchar(64),
    verified_at            timestamptz,
    effective_from         timestamptz,
    invalidated_by         varchar(64),
    invalidated_at         timestamptz,
    invalidation_reason    text,
    -- Una revisione deve dire perche' esiste (ISO/IEC 17025 § 7.8.8).
    CHECK (supersedes_id IS NULL OR amendment_reason IS NOT NULL)
);

-- Il numero e' univoco per laboratorio e revisione.
CREATE UNIQUE INDEX certificate_number_unique
    ON metrology.certificate (kind, COALESCE(lab_company_id, 0), number, revision);
CREATE INDEX idx_certificate_subject ON metrology.certificate (subject_type, subject_id);
CREATE INDEX idx_certificate_status ON metrology.certificate (status);

