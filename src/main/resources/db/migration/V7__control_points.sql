-- Fase 4 del piano metrologico, passi 4.2 e 4.3: punti di controllo, profili, conformita'
-- [S §5.6].
--
-- Il profilo si assegna al punto di controllo, mai al sensore. Il punto di controllo ha una
-- storia di assegnazioni: quando una MU viene sostituita si chiude un'assegnazione e se ne apre
-- un'altra, e la serie del punto di controllo resta continua.

CREATE TABLE metrology.control_point (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_sub           varchar(64)       NOT NULL,
    company_id          bigint            REFERENCES metrology.client_company(id),
    name                varchar(120)      NOT NULL,
    location            varchar(200),
    process             varchar(120),
    profile_template_id integer           NOT NULL,
    profile_version     varchar(32)       NOT NULL,
    -- Il profilo alla versione citata. Le versioni pubblicate sono immutabili, e il consumer di
    -- sample-converted non ha il token di un utente per chiederle al registro.
    profile             jsonb             NOT NULL,
    -- Eccezioni del cliente: possono solo restringere i limiti del profilo, con il motivo.
    overrides           jsonb,
    -- I limiti in vigore (profilo ristretto dalle eccezioni), per il consumer e per Grafana.
    -- Entrambi nulli per un profilo a clima storico: i limiti cambiano col giorno dell'anno.
    limit_low           double precision,
    limit_high          double precision,
    created_by          varchar(64)       NOT NULL,
    created_at          timestamptz       NOT NULL DEFAULT now(),
    archived_at         timestamptz
);
CREATE INDEX idx_control_point_owner ON metrology.control_point (owner_sub);

CREATE TABLE metrology.control_point_assignment (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    control_point_id    bigint            NOT NULL REFERENCES metrology.control_point(id),
    calibrated_item_id  bigint            NOT NULL REFERENCES metrology.calibrated_item(id),
    metric              varchar(16)       NOT NULL DEFAULT 'mean',
    from_ts             timestamptz       NOT NULL,
    to_ts               timestamptz,
    created_by          varchar(64)       NOT NULL,
    created_at          timestamptz       NOT NULL DEFAULT now(),
    CHECK (to_ts IS NULL OR to_ts > from_ts)
);
-- Un punto di controllo ha un esemplare alla volta, e un esemplare (con la sua metrica) sorveglia
-- un punto di controllo alla volta.
CREATE UNIQUE INDEX uq_assignment_open_point ON metrology.control_point_assignment (control_point_id) WHERE to_ts IS NULL;
CREATE UNIQUE INDEX uq_assignment_open_item ON metrology.control_point_assignment (calibrated_item_id, metric) WHERE to_ts IS NULL;
CREATE INDEX idx_assignment_item ON metrology.control_point_assignment (calibrated_item_id);

-- Lo stato del consumer di sample-converted per punto di controllo. L'ultimo istante visto rende
-- il consumer idempotente: un evento ripetuto o in ritardo non riapre un'escursione.
CREATE TABLE metrology.conformity_state (
    control_point_id    bigint PRIMARY KEY REFERENCES metrology.control_point(id),
    last_window_end     timestamptz,
    last_value          double precision,
    last_verdict        varchar(16),
    -- Da quando i valori non sono piu' conformi (zona di guardia o oltre): la zona di guardia
    -- prolungata apre un'escursione se il profilo lo chiede.
    guard_since         timestamptz,
    updated_at          timestamptz       NOT NULL DEFAULT now()
);

-- Le medie orarie del punto di controllo: la storia che serve al clima storico (EN 15757).
CREATE TABLE metrology.control_point_hourly (
    control_point_id    bigint            NOT NULL REFERENCES metrology.control_point(id),
    hour_start          timestamptz       NOT NULL,
    value_sum           double precision  NOT NULL,
    samples             integer           NOT NULL,
    PRIMARY KEY (control_point_id, hour_start)
);

-- Il clima storico calcolato da quella storia: la media mobile per giorno dell'anno e la banda
-- delle fluttuazioni a breve termine.
CREATE TABLE metrology.control_point_climate (
    control_point_id    bigint PRIMARY KEY REFERENCES metrology.control_point(id),
    computed_at         timestamptz       NOT NULL,
    history_from        timestamptz       NOT NULL,
    history_to          timestamptz       NOT NULL,
    band_low            double precision  NOT NULL,
    band_high           double precision  NOT NULL,
    daily               jsonb             NOT NULL
);

-- Grafana disegna la serie del punto di controllo unendo le assegnazioni ai campioni di
-- sensor-manager (grafana.sample_series): gli servono queste tabelle in sola lettura.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'grafana_ro') THEN
        GRANT USAGE ON SCHEMA metrology TO grafana_ro;
        GRANT SELECT ON metrology.control_point, metrology.control_point_assignment, metrology.calibrated_item TO grafana_ro;
    END IF;
END
$$;
