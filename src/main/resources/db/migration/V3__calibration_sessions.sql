-- Fase 3 del piano (passo 3.2): le sessioni di taratura e i loro gradini [S §5.2, §5.3; M4].
--
-- Il Raspberry apre la sessione via REST e da quel momento pubblica i gradini su MQTT con
-- `calib_id` uguale all'id della sessione. kafka-stream li porta sul topic `calibrations`, e il
-- consumer di questo servizio li salva qui, scartando i duplicati: e' la logica di assemblaggio
-- di KafkaCalibrationConsumer di Mario, riscritta per sessione invece che per stringa.

CREATE TABLE metrology.calibration_session (
    id                        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mu_extended_id            bigint       NOT NULL,
    reference_standard_id     bigint       NOT NULL REFERENCES metrology.reference_standard(id),
    -- Il certificato del campione valido all'apertura: le sue correzioni entrano nel fit.
    reference_certificate_id  bigint       REFERENCES metrology.certificate(id),
    procedure_template_id     integer      NOT NULL,
    procedure_version         varchar(16)  NOT NULL,
    operator_sub              varchar(64)  NOT NULL,
    started_at                timestamptz  NOT NULL DEFAULT now(),
    ended_at                  timestamptz,
    ambient                   jsonb,
    status                    varchar(16)  NOT NULL DEFAULT 'OPEN'
        CHECK (status IN ('OPEN', 'AS_FOUND_DONE', 'ADJUSTED', 'AS_LEFT_DONE', 'CLOSED', 'ABORTED')),
    adjustment_applied        boolean,
    notes                     text
);
CREATE INDEX idx_calibration_session_mu ON metrology.calibration_session (mu_extended_id);

-- Gli esemplari coinvolti: una sessione puo' tarare piu' sensori della stessa MU.
CREATE TABLE metrology.session_item (
    session_id          bigint NOT NULL REFERENCES metrology.calibration_session(id),
    calibrated_item_id  bigint NOT NULL REFERENCES metrology.calibrated_item(id),
    PRIMARY KEY (session_id, calibrated_item_id)
);

-- Un gradino: un setpoint della procedura, per un sensore, in una fase. La chiave unica e'
-- l'idempotenza: lo stesso gradino consegnato due volte da Kafka non crea una riga in piu'.
CREATE TABLE metrology.session_step (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id            bigint            NOT NULL REFERENCES metrology.calibration_session(id),
    phase                 varchar(16)       NOT NULL CHECK (phase IN ('AS_FOUND', 'AS_LEFT')),
    step_index            integer           NOT NULL,
    sensor_index          integer           NOT NULL,
    setpoint              double precision,
    minutes               integer,
    total_steps           integer,
    started_at            timestamptz,
    dwell_started_at      timestamptz,
    sensor_sampling_freq  integer,
    -- Letture del riferimento e campioni grezzi del sensore, gia' decodificati dal base64.
    reference_readings    jsonb             NOT NULL,
    sensor_samples        jsonb             NOT NULL,
    stable                boolean,
    received_at           timestamptz       NOT NULL DEFAULT now(),
    UNIQUE (session_id, phase, step_index, sensor_index)
);
