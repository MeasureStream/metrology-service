-- Fase 4 del piano metrologico, passo 4.4: escursioni e non conformita' (criticita' M7) [S §5.6].
--
-- Due non conformita' diverse, con responsabili e azioni diversi:
-- - di PROCESSO: un'escursione del punto di controllo oltre i limiti del profilo. Serve
--   un'azione correttiva del cliente (HACCP), lo strumento puo' essere perfetto;
-- - di STRUMENTO: un as-found fuori tolleranza in taratura. Decide il laboratorio (regolare,
--   riparare, ritirare), e i dati misurati da quell'esemplare dall'ultima taratura vanno
--   rivalutati (fase 5).

CREATE TABLE metrology.nonconformity (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type                varchar(16)       NOT NULL CHECK (type IN ('PROCESS', 'INSTRUMENT')),
    control_point_id    bigint            REFERENCES metrology.control_point(id),
    calibrated_item_id  bigint            REFERENCES metrology.calibrated_item(id),
    -- Che cosa e' successo, nei termini dell'oggetto: escursione, risultato di taratura, punti.
    subject             jsonb             NOT NULL,
    title               varchar(200)      NOT NULL,
    detected_at         timestamptz       NOT NULL,
    severity            varchar(8)        NOT NULL CHECK (severity IN ('MINOR', 'MAJOR')),
    state               varchar(16)       NOT NULL DEFAULT 'OPEN' CHECK (state IN ('OPEN', 'ACKNOWLEDGED', 'RESOLVED')),
    -- Di chi e' l'oggetto: decide chi vede la non conformita'.
    owner_sub           varchar(64),
    assignee_sub        varchar(64),
    acknowledged_by     varchar(64),
    acknowledged_at     timestamptz,
    decision            varchar(24)       CHECK (decision IN ('ACCEPT_AS_IS', 'ADJUST', 'REPAIR', 'RETIRE', 'CORRECTIVE_ACTION')),
    decision_reason     text,
    decided_by          varchar(64),
    decided_at          timestamptz,
    created_at          timestamptz       NOT NULL DEFAULT now()
);
CREATE INDEX idx_nonconformity_state ON metrology.nonconformity (state);
CREATE INDEX idx_nonconformity_point ON metrology.nonconformity (control_point_id);
CREATE INDEX idx_nonconformity_item ON metrology.nonconformity (calibrated_item_id);

-- Valori non conformi consecutivi: inizio, fine, picco e grado-minuti oltre il limite.
CREATE TABLE metrology.excursion (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    control_point_id    bigint            NOT NULL REFERENCES metrology.control_point(id),
    -- LIMIT: oltre il limite anche tenendo conto dell'incertezza. GUARD_ZONE: zona di guardia
    -- piu' lunga di quanto il profilo ammette.
    kind                varchar(16)       NOT NULL CHECK (kind IN ('LIMIT', 'GUARD_ZONE')),
    side                varchar(8)        NOT NULL CHECK (side IN ('HIGH', 'LOW')),
    limit_value         double precision  NOT NULL,
    started_at          timestamptz       NOT NULL,
    ended_at            timestamptz,
    peak                double precision  NOT NULL,
    peak_at             timestamptz       NOT NULL,
    degree_minutes      double precision  NOT NULL DEFAULT 0,
    samples             integer           NOT NULL DEFAULT 1,
    state               varchar(8)        NOT NULL DEFAULT 'OPEN' CHECK (state IN ('OPEN', 'CLOSED')),
    nonconformity_id    bigint            REFERENCES metrology.nonconformity(id),
    created_at          timestamptz       NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uq_excursion_open ON metrology.excursion (control_point_id) WHERE state = 'OPEN';
CREATE INDEX idx_excursion_point ON metrology.excursion (control_point_id, started_at);

