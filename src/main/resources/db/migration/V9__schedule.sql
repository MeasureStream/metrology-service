-- Fase 4 del piano metrologico, passo 4.5: lo scadenzario [S §5.7].
--
-- Una riga per oggetto e tipo di scadenza. Si ricalcola a ogni attivazione di un certificato e
-- ogni notte; i promemoria a 90, 30 e 0 giorni partono una volta sola per scadenza: quando la
-- scadenza cambia (certificato nuovo), l'elenco dei livelli gia' avvisati si azzera.

CREATE TABLE metrology.schedule_item (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_type        varchar(16)       NOT NULL CHECK (subject_type IN ('ITEM', 'REFERENCE')),
    subject_id          bigint            NOT NULL,
    kind                varchar(24)       NOT NULL CHECK (kind IN ('CALIBRATION', 'INTERMEDIATE_CHECK')),
    due_at              timestamptz,
    interval_days       integer,
    last_done_at        timestamptz,
    -- Da dove viene la scadenza: certificato, profilo del punto di controllo, intervallo dell'esemplare.
    source              varchar(200),
    owner_sub           varchar(64),
    notified_levels     jsonb             NOT NULL DEFAULT '[]',
    updated_at          timestamptz       NOT NULL DEFAULT now(),
    UNIQUE (subject_type, subject_id, kind)
);
CREATE INDEX idx_schedule_due ON metrology.schedule_item (due_at);
