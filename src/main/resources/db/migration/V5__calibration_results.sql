-- Fase 3 del piano (passo 3.7): il risultato del motore per ogni esemplare, la decisione di
-- regolazione e il legame con il certificato interno che ne nasce [S §5.2, §5.3].

CREATE TABLE metrology.calibration_result (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id                 uuid              NOT NULL REFERENCES metrology.calibration_job(id),
    session_id             bigint            REFERENCES metrology.calibration_session(id),
    calibrated_item_id     bigint            NOT NULL REFERENCES metrology.calibrated_item(id),
    function               jsonb,
    covariance             jsonb,
    calibrated_min         double precision,
    calibrated_max         double precision,
    calibrated_dsi         varchar(80),
    points                 jsonb,
    budget                 jsonb,
    conformity             jsonb,
    suggested_decision     varchar(24),
    -- La decisione del tecnico: regolare o no, con il motivo [S §5.3 punto 4].
    decision               varchar(24)       CHECK (decision IN ('ADJUST', 'NO_ADJUSTMENT', 'REPAIR', 'RETIRE')),
    decision_reason        text,
    decided_by             varchar(64),
    decided_at             timestamptz,
    adjustment_applied     boolean,
    -- Block A (fase 6): immagine e CRC da scrivere sulla MU, e la conferma del Raspberry.
    block_a_image          bytea,
    block_a_crc            varchar(8),
    block_a_crc_confirmed  boolean,
    block_a_written_at     timestamptz,
    created_at             timestamptz       NOT NULL DEFAULT now(),
    -- Idempotenza: un risultato consegnato due volte non crea una seconda riga.
    UNIQUE (job_id, calibrated_item_id)
);
CREATE INDEX idx_calibration_result_item ON metrology.calibration_result (calibrated_item_id);

ALTER TABLE metrology.certificate
    ADD CONSTRAINT certificate_calibration_result_fk
    FOREIGN KEY (calibration_result_id) REFERENCES metrology.calibration_result(id);
