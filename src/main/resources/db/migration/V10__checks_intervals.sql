-- Fase 5 del piano metrologico, passo 5.2: verifiche intermedie, carte di controllo, proposte
-- d'intervallo [S §5.7].

-- Una verifica intermedia: l'esemplare confrontato con un riferimento in un punto, fra due
-- tarature. Si salvano errore, incertezze, numero En ed esito.
CREATE TABLE metrology.intermediate_check (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    calibrated_item_id      bigint            NOT NULL REFERENCES metrology.calibrated_item(id),
    checked_at              timestamptz       NOT NULL,
    reference_value         double precision  NOT NULL,
    -- Incertezza estesa del riferimento, con il suo fattore di copertura.
    reference_u             double precision  NOT NULL,
    reference_k             double precision  NOT NULL DEFAULT 2,
    indicated_value         double precision  NOT NULL,
    -- Incertezza estesa dell'indicazione (k = 2); se non e' data, quella di targa (2·MPE/√3).
    indicated_u             double precision  NOT NULL,
    error                   double precision  NOT NULL,
    -- En = errore / √(U_ind² + U_ref²): |En| ≤ 1 vuol dire indicazione e riferimento compatibili.
    en                      double precision  NOT NULL,
    tolerance               double precision,
    verdict                 varchar(16)       NOT NULL CHECK (verdict IN ('PASS', 'FAIL', 'UNDECIDED')),
    reference_standard_id   bigint            REFERENCES metrology.reference_standard(id),
    reference_description   varchar(200),
    source                  varchar(16)       NOT NULL DEFAULT 'UI' CHECK (source IN ('UI', 'RASPBERRY')),
    performed_by            varchar(64)       NOT NULL,
    notes                   text,
    nonconformity_id        bigint            REFERENCES metrology.nonconformity(id),
    created_at              timestamptz       NOT NULL DEFAULT now()
);
CREATE INDEX idx_intermediate_check_item ON metrology.intermediate_check (calibrated_item_id, checked_at);

-- La proposta di un nuovo intervallo di taratura secondo OIML D 10 (metodo a gradini). Lo
-- scadenzario non la applica da solo: la accetta o la respinge chi ne ha il ruolo.
CREATE TABLE metrology.interval_proposal (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    calibrated_item_id      bigint            NOT NULL REFERENCES metrology.calibrated_item(id),
    certificate_id          bigint            REFERENCES metrology.certificate(id),
    method                  varchar(32)       NOT NULL DEFAULT 'OIML_D10_STAIRCASE',
    current_days            integer           NOT NULL,
    proposed_days           integer           NOT NULL,
    -- Il rapporto fra l'errore as-found piu' grande e la tolleranza che ha deciso la proposta.
    ratio                   double precision,
    reason                  text              NOT NULL,
    state                   varchar(16)       NOT NULL DEFAULT 'PROPOSED' CHECK (state IN ('PROPOSED', 'ACCEPTED', 'REJECTED')),
    decided_by              varchar(64),
    decided_at              timestamptz,
    decision_reason         text,
    created_at              timestamptz       NOT NULL DEFAULT now()
);
CREATE INDEX idx_interval_proposal_item ON metrology.interval_proposal (calibrated_item_id, created_at);

